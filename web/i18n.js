let lang = 'pt';
try {
  const q = new URLSearchParams(location.search).get('lang');
  const saved = q || localStorage.getItem('v2m:lang');
  lang = saved === 'en' ? 'en' : saved === 'pt' ? 'pt'
    : (String(navigator.language || '').toLowerCase().startsWith('pt') ? 'pt' : 'en');
} catch (e) { /* storage indisponivel: fica pt */ }
if (lang === 'en') {
  try { localStorage.setItem('v2m:lang', 'en'); } catch (e) { /* ok */ }
}

export function getLang() { return lang; }

export function setLang(l) {
  lang = (l === 'en') ? 'en' : 'pt';
  try { localStorage.setItem('v2m:lang', lang); } catch (e) { /* ok */ }
}

export function t(key, vars) {
  const d = DICT[lang] || {};
  let s = (d[key] !== undefined) ? d[key]
    : (DICT.pt[key] !== undefined ? DICT.pt[key] : key);
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}

export function applyStatic(root) {
  const r = root || document;
  r.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  r.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  r.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  r.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
}

export function langSwitcher(id) {
  const host = document.getElementById(id || 'lang-switch');
  if (!host) return;
  host.innerHTML = '';
  for (const l of ['pt', 'en']) {
    const b = document.createElement('button');
    b.type = 'button';
    b.className = 'lang-btn' + (l === lang ? ' active' : '');
    b.textContent = l.toUpperCase();
    b.title = l === 'pt' ? 'Português (Brasil)' : 'English';
    b.addEventListener('click', () => {
      if (l === lang) return;
      setLang(l);
      // US-08: em navegadores sem localStorage (storage bloqueado), persiste
      // a escolha na propria URL (?lang=) -- o reload mantem o idioma.
      try {
        const u = new URL(location.href);
        u.searchParams.set('lang', l);
        location.replace(u.toString());
        return;
      } catch (e) { /* url indisponivel: cai no reload simples */ }
      location.reload();
    });
    host.appendChild(b);
  }
}
